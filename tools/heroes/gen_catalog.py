#!/usr/bin/env python3
"""
Regenerates the server's hero catalog (domain/rules/HeroCatalog.kt) from the client's hero data.

    python3 tools/heroes/gen_catalog.py ../Arena-Game-Mobile/unity/Assets/Resources/Data

The directory holds the two files heroes are edited in (the mobile repo): people.json (every hero: id, name, people,
group, position, role, number, power) and arena_skills.json (the Arena v4 kits of the eleven humans: four skills s0..s3,
alternates aN, passives pN, the hero's energy colour). The server keeps only what it needs; a hero without a kit in
arena_skills.json (the peoples' heroes, p012+) has `hasKit` false and cannot play the Arena yet. Run this after either
file changes and commit the result. The unlock rules (start six, story chapters, prices) live in rules/Heroes.kt, not here.
"""
import json, os, sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
src = sys.argv[1]
people = json.load(open(os.path.join(src, "people.json"), encoding="utf-8"))
arena = json.load(open(os.path.join(src, "arena_skills.json"), encoding="utf-8"))
out = os.path.join(os.path.dirname(__file__), "../../server/src/main/kotlin/com/arenacity/domain/rules/HeroCatalog.kt")

PEOPLE = {"human": "null", "beast": "People.BEAST", "stone": "People.STONE", "android": "People.ANDROID", "shadow": "People.SHADOW"}

def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

def klist(items):
    return "listOf(" + ", ".join(kstr(i) for i in items) + ")"

kits = {h["id"]: h for h in arena["heroes"]}
rows = []
for h in people["people"]:
    kit = kits.get(h["id"])
    if kit is not None:
        skills = sorted((s for s in kit["skills"] if s["role"] == "skill"), key=lambda s: s["slot"])
        if [s["slot"] for s in skills] != [0, 1, 2, 3]:
            sys.exit(f"{h['id']}: expected skills in slots 0..3, got {[s['slot'] for s in skills]}")
        skill_ids = [s["id"] for s in skills]
        alternates = [s["id"] for s in kit["skills"] if s["role"] == "alt"]
        passives = [s["id"] for s in kit["skills"] if s["role"] == "passive"]
        colour = kstr(kit["colour"])
        power = kit.get("power") or h.get("power", "")
        if kit["number"] != h["number"] or kit["name"] != h["name"]:
            sys.exit(f"{h['id']}: people.json and arena_skills.json disagree on the name or number")
    else:
        skill_ids, alternates, passives, colour, power = [], [], [], "null", h.get("power", "")
    rows.append(f"        HeroSpec({kstr(h['id'])}, {kstr(h['name'])}, {PEOPLE[h['people']]}, HeroGroup.{h['group'].upper()}, "
                f"{kstr(h['position'])}, {kstr(h['role'])}, {kstr(power)}, {int(h['number'])}, {colour}, {klist(skill_ids)}, {klist(alternates)}, {klist(passives)}),")

body = "\n".join(rows)
open(out, "w", encoding="utf-8").write(f"""package com.arenacity.domain.rules

import com.arenacity.domain.model.HeroGroup
import com.arenacity.domain.model.HeroSpec
import com.arenacity.domain.model.People

// GENERATED by tools/heroes/gen_catalog.py from the mobile repo's unity/Assets/Resources/Data/people.json (version
// {people.get('version')}) and arena_skills.json (version {arena.get('version')}): do not edit by hand, edit those and regenerate.

/**
 * Every hero of the game (docs/claude/HEROES-INSTEAD-OF-CARDS.md in the mobile repo) with its Arena v4 kit (the eleven
 * humans; docs/claude/ARENA-SKILLS-V4.md); the unlock rules are in [Heroes].
 */
object HeroCatalog {{
    val ALL: List<HeroSpec> = listOf(
{body}
    )
    private val byId = ALL.associateBy {{ it.id }}
    fun of(id: String): HeroSpec? = byId[id]
    /** The heroes with an Arena kit: the only ones that play the Arena (and are sold) for now. */
    val WITH_KIT: List<HeroSpec> = ALL.filter {{ it.hasKit }}
}}
""")
print(f"{len(rows)} heroes ({len(kits)} with an Arena kit) -> {os.path.normpath(out)}")
