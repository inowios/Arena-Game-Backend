#!/usr/bin/env python3
"""
Regenerates the server's hero catalog (domain/rules/HeroCatalog.kt) from the client's hero data.

    python3 tools/heroes/gen_catalog.py ../Arena-Game-Mobile/unity/Assets/Resources/Data/people.json

people.json (the mobile repo) is the one place heroes are edited; the server keeps only what it needs (id, name, people,
group, position, role, power, number and the ids of the three advanced skills). Run this after people.json changes and
commit the result. The unlock rules (start six, story chapters, prices) live in rules/Heroes.kt, not here.
"""
import json, os, sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
src = sys.argv[1]
data = json.load(open(src, encoding="utf-8"))
out = os.path.join(os.path.dirname(__file__), "../../server/src/main/kotlin/com/arenacity/domain/rules/HeroCatalog.kt")

PEOPLE = {"human": "null", "beast": "People.BEAST", "stone": "People.STONE", "android": "People.ANDROID", "shadow": "People.SHADOW"}

def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

rows = []
for h in data["people"]:
    adv = sorted((s for s in h["skills"] if s["unlockOvr"] > 0), key=lambda s: s["unlockOvr"])
    if [s["unlockOvr"] for s in adv] != [65, 75, 85]:
        sys.exit(f"{h['id']}: expected advanced skills at OVR 65/75/85, got {[s['unlockOvr'] for s in adv]}")
    skills = ", ".join(kstr(s["id"]) for s in adv)
    rows.append(f"        HeroSpec({kstr(h['id'])}, {kstr(h['name'])}, {PEOPLE[h['people']]}, HeroGroup.{h['group'].upper()}, "
                f"{kstr(h['position'])}, {kstr(h['role'])}, {kstr(h['power'])}, {int(h['number'])}, listOf({skills})),")

body = "\n".join(rows)
open(out, "w", encoding="utf-8").write(f"""package com.arenacity.domain.rules

import com.arenacity.domain.model.HeroGroup
import com.arenacity.domain.model.HeroSpec
import com.arenacity.domain.model.People

// GENERATED by tools/heroes/gen_catalog.py from the mobile repo's unity/Assets/Resources/Data/people.json
// (version {data.get('version')}): do not edit by hand, edit people.json and regenerate.

/** Every hero of the game (docs/claude/HEROES-INSTEAD-OF-CARDS.md in the mobile repo); the unlock rules are in [Heroes]. */
object HeroCatalog {{
    val ALL: List<HeroSpec> = listOf(
{body}
    )
    private val byId = ALL.associateBy {{ it.id }}
    fun of(id: String): HeroSpec? = byId[id]
}}
""")
print(f"{len(rows)} heroes -> {os.path.normpath(out)}")
